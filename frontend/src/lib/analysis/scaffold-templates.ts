// NOTE: no CI-workflow generator here on purpose — CI/CD pipelines are owned
// by the in-project deploy flow (deploy_my_app / CI-CD tab), which wires the
// registry auth, kubeconfig secrets and CD stages the bare analysis can't.

export function envExampleFor(envVars: EnvVarInfo[]): string {
  const lines = [
    "# Environment variables this app reads — generated by DeepAgent from the source.",
    "# Copy to .env and fill in real values. Secrets marked with (secret).",
    "",
  ];
  for (const v of envVars) {
    lines.push(`${v.name}=${v.secret ? " # (secret)" : ""}`);
  }
  return lines.join("\n") + "\n";
}

